def fmt(value: Any, unit: str = "") -> str:
    """A metric value for the table; None is n/a."""
    if value is None:
        return "n/a"
    if isinstance(value, float) and value.is_integer() and unit != "×":
        value = int(value)
    return f"{value:,}{unit}" if isinstance(value, int) else f"{value}{unit}"


def _table(rows: list[tuple[str, str, str, str]], values: dict[str, Any]) -> list[str]:
    lines = ["| Metric | Result | Target |", "|---|---|---|"]
    lines += [
        f"| {label} | {fmt(values[key], unit)} | {target} |" for label, key, target, unit in rows
    ]
    return lines


def render_summary(metrics: dict[str, Any], source: str, k: int) -> str:
    """The markdown report for every model in `metrics`."""
    out = [
        "# OpenRx eval results",
        "",
        f"Generated by `openrx eval report` from `{source}` (k = {k}, replay mode, "
        "temperature 0). Metric definitions: docs/design.md §6. Deterministic scoring only; the "
        "LLM judge, injection tasks and a second model are not in v1 (D-017).",
    ]
    for model, m in metrics.items():
        overall = m["overall"]
        q, e, r, lat = (
            overall["quality"],
            overall["efficiency"],
            overall["reliability"],
            overall["latency"],
        )
        out += [
            "",
            f"## Model `{model}`",
            "",
            f"{q['tasks']} tasks, {q['trials']} trials, {r['tool_calls']} tool calls, "
            f"{m['new_fixtures']} fixture(s) recorded during the run.",
            "",
        ]
        out += ["### Quality (§6.1)", "", *_table(_QUALITY, q), ""]
        out += ["### Efficiency (§6.2)", "", *_table(_EFFICIENCY, e), ""]
        out += ["### Reliability (§6.3)", "", *_table(_RELIABILITY, r), ""]
        out += [
            "### Latency (§6.4, as the agent sees it)",
            "",
            "| Path | p50 | p95 | p99 |",
            "|---|---|---|---|",
        ]
        for label, key, unit in [
            ("`search` call (ms)", "search_ms", ""),
            ("`execute` call (ms)", "execute_ms", ""),
            ("Full task (s)", "task_s", ""),
            ("  of which model (s)", "model_s", ""),
            ("  of which tools (s)", "tool_s", ""),
        ]:
            p = lat[key]
            out.append(
                f"| {label} | {fmt(p['p50'], unit)} | {fmt(p['p95'], unit)} | "
                f"{fmt(p['p99'], unit)} |"
            )
        out += [
            "",
            "### By category",
            "",
            "| Category | Tasks | pass@1 | pass^k | Partial | Tokens p50 | Turns p50 | "
            "Data reduction |",
            "|---|---|---|---|---|---|---|---|",
        ]
        for category, c in m["by_category"].items():
            cq, ce = c["quality"], c["efficiency"]
            out.append(
                f"| {category} | {cq['tasks']} | {fmt(cq['pass_at_1'], '%')} | "
                f"{fmt(cq['pass_all_k'], '%')} | {fmt(cq['partial_score'])} | "
                f"{fmt(ce['tokens_p50'])} | {fmt(ce['turns_p50'])} | "
                f"{fmt(ce['data_reduction'], '×')} |"
            )
    out += ["", "![Pass rate by category](pass_by_category.png)", ""]
    return "\n".join(out)


def failures(records: list[dict[str, Any]]) -> str:
    """A markdown list of every failed trial, for reading what went wrong."""
    lines = ["| Task | Attempt | Why | Answer (start) |", "|---|---|---|---|"]
    for r in sorted(records, key=lambda r: (r["task"], r["attempt"])):
        if r["passed"]:
            continue
        why = r["crash"] or r.get("detail") or "failed"
        answer = (r["answer"] or "").replace("\n", " ").replace("|", "\\|")[:120]
        lines.append(f"| {r['task']} | {r['attempt']} | {why.replace('|', '/')} | {answer} |")
    return "\n".join(lines) if len(lines) > 2 else "No failed trials."


def chart_pass_by_category(metrics: dict[str, Any], path: Path) -> None:
    """A horizontal bar chart of pass rate over all trials per category, one model."""
    import matplotlib

    matplotlib.use("Agg")
    import matplotlib.pyplot as plt

    model, m = next(iter(metrics.items()))
    rows = sorted(m["by_category"].items(), key=lambda kv: kv[1]["quality"]["pass_rate"] or 0)
    names = [name.replace("_", " ") for name, _ in rows]
    values = [c["quality"]["pass_rate"] or 0 for _, c in rows]

    fig, ax = plt.subplots(figsize=(6.4, 0.5 * len(rows) + 1.1), dpi=150)
    fig.patch.set_facecolor("#fcfcfb")
    ax.set_facecolor("#fcfcfb")
    ax.barh(names, values, color="#2a78d6", height=0.6)
    for y, v in enumerate(values):
        ax.text(v + 1.5, y, f"{v:g}%", va="center", fontsize=9, color="#0b0b0b")
    ax.set_xlim(0, 110)
    ax.set_xticks([0, 25, 50, 75, 100])
    ax.tick_params(colors="#52514e", labelsize=9, length=0)
    ax.grid(axis="x", color="#e4e3df", linewidth=0.8)
    ax.set_axisbelow(True)
    for side in ("top", "right", "left", "bottom"):
        ax.spines[side].set_visible(False)
    ax.set_title(
        f"Pass rate by task category ({model}, all trials)",
        fontsize=10,
        color="#0b0b0b",
        loc="left",
    )
    fig.tight_layout()
    path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(path)
    plt.close(fig)
