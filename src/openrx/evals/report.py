"""Write results/summary.md (and a chart) from a runs file (docs/design.md §12.3).

The summary is plain markdown so it reads well on GitHub and diffs cleanly; the README's
results section quotes it. Each metric is shown next to its docs/design.md §6 target, and a
metric with nothing to count shows "n/a" rather than a made-up zero.
"""

