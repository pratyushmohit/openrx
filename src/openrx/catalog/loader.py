"""Load catalog YAML files into validated `Source` objects.

Loading is where untrusted text becomes trusted data (see schema.py), so every problem
is reported with the file and the exact place in it. All files are checked before
failing, so one run shows every problem instead of one per run.

Layout of a catalog root (the package's own one is CATALOG_DIR):

    sources/<source>.yaml               hand-written
    examples/<source>/<endpoint>.json   generated by `catalog capture-examples` (D-009)
"""

import json
from collections.abc import Iterator, Mapping
from dataclasses import dataclass
from pathlib import Path
from types import MappingProxyType
from typing import Any

import yaml
from pydantic import ValidationError
from pydantic_core import ErrorDetails

from openrx.catalog.schema import Source

# The catalog ships inside the package (D-008): sources/ and examples/ next to this file.
CATALOG_DIR = Path(__file__).parent


@dataclass(frozen=True)
class Problem:
    """One thing wrong with a catalog file."""

    file: str
    location: str
    message: str

    def __str__(self) -> str:
        """Format as `file: location: message`, one line, for terminal output."""
        where = f"{self.file}: {self.location}" if self.location else self.file
        return f"{where}: {self.message}"


class CatalogError(Exception):
    """The catalog could not be loaded. `problems` lists everything that is wrong."""

    def __init__(self, problems: list[Problem]) -> None:
        """Create the error from a non-empty list of problems."""
        self.problems = problems
        super().__init__("\n".join(str(p) for p in problems))


@dataclass(frozen=True)
class Catalog:
    """All sources, by id. Read-only."""

    sources: Mapping[str, Source]

    def source(self, source_id: str) -> Source | None:
        """Return the source with this id, or None."""
        return self.sources.get(source_id)

    def __iter__(self) -> Iterator[Source]:
        """Iterate over sources in id order."""
        return iter(self.sources[k] for k in sorted(self.sources))


def load_catalog(root: Path = CATALOG_DIR) -> Catalog:
    """Load and validate every source in `root/sources`, with its examples attached.

    Raises:
        CatalogError: if any file is invalid, or there are no source files at all.
    """
    sources, problems = _load_all(root)
    if problems:
        raise CatalogError(problems)
    return Catalog(MappingProxyType(sources))


def lint_catalog(root: Path = CATALOG_DIR) -> list[Problem]:
    """Check the catalog more strictly than loading does; return all problems.

    On top of everything `load_catalog` checks: every endpoint has an example (M1 exit
    criterion; drafts without one still load), and no example file is left over from
    a removed or renamed endpoint.
    """
    sources, problems = _load_all(root)
    for source in sources.values():
        for index, endpoint in enumerate(source.endpoints):
            if endpoint.example_response is None:
                problems.append(
                    Problem(
                        f"{source.id}.yaml",
                        f"endpoints[{index}] ({endpoint.id})",
                        f"missing example: run 'openrx catalog capture-examples {source.id}'",
                    )
                )
    problems.extend(_orphan_examples(root, sources))
    return problems


def read_yaml(path: Path) -> Any:
    """Parse a YAML file safely (no Python objects) and reject duplicate keys.

    Raises:
        yaml.YAMLError: if the file is not valid YAML or repeats a key.
    """
    return yaml.load(path.read_text(encoding="utf-8"), Loader=_UniqueKeyLoader)


def example_path(root: Path, source_id: str, endpoint_id: str) -> Path:
    """Where the example response for an endpoint is stored."""
    return root / "examples" / source_id / f"{endpoint_id}.json"


def load_source(path: Path, examples_root: Path | None = None) -> Source:
    """Load and validate one catalog file.

    Args:
        path: The source's YAML file.
        examples_root: Catalog root whose `examples/` folder holds this source's
            example responses. None loads the source without examples.

    Raises:
        CatalogError: if the file is not valid YAML, does not match the schema, or one
            of its example files is broken.
    """
    try:
        data = read_yaml(path)
    except yaml.YAMLError as e:
        raise CatalogError([Problem(path.name, "", f"invalid YAML: {_yaml_message(e)}")]) from None
    if not isinstance(data, dict):
        raise CatalogError(
            [Problem(path.name, "", "top level must be a mapping (key: value pairs)")]
        )

    problems = _inline_examples(path, data)
    if examples_root is not None:
        problems += _attach_examples(examples_root, data)
    if problems:
        raise CatalogError(problems)

    try:
        return Source.model_validate(data)
    except ValidationError as e:
        raise CatalogError(
            [
                Problem(path.name, _location(err["loc"], data), _message(err))
                for err in _root_causes(e)
            ]
        ) from None


def _load_all(root: Path) -> tuple[dict[str, Source], list[Problem]]:
    sources_dir = root / "sources"
    files = sorted(sources_dir.glob("*.yaml")) if sources_dir.is_dir() else []
    if not files:
        return {}, [Problem(str(sources_dir), "", "no catalog files (*.yaml) found")]

    sources: dict[str, Source] = {}
    problems: list[Problem] = []
    for path in files:
        try:
            source = load_source(path, examples_root=root)
        except CatalogError as e:
            problems.extend(e.problems)
            continue
        # Filenames are unique, so this also guarantees unique source ids.
        if source.id != path.stem:
            problems.append(
                Problem(path.name, "id", f"source id {source.id!r} must match the file name")
            )
            continue
        sources[source.id] = source
    return sources, problems


def _endpoint_dicts(data: dict[str, Any]) -> list[tuple[int, dict[str, Any]]]:
    endpoints = data.get("endpoints")
    if not isinstance(endpoints, list):
        return []
    return [(i, e) for i, e in enumerate(endpoints) if isinstance(e, dict)]


def _inline_examples(path: Path, data: dict[str, Any]) -> list[Problem]:
    """Examples have one home, their own file (D-009), so YAML must not contain them."""
    return [
        Problem(
            path.name,
            _location(("endpoints", i, "example_response"), data),
            "examples live in examples/<source>/<endpoint>.json, not in YAML",
        )
        for i, endpoint in _endpoint_dicts(data)
        if "example_response" in endpoint
    ]


def _attach_examples(root: Path, data: dict[str, Any]) -> list[Problem]:
    """Read each endpoint's example file, if any, into the raw data before validation."""
    source_id = data.get("id")
    if not isinstance(source_id, str):
        return []  # schema validation reports the missing id
    problems = []
    for _, endpoint in _endpoint_dicts(data):
        endpoint_id = endpoint.get("id")
        if not isinstance(endpoint_id, str):
            continue
        file = example_path(root, source_id, endpoint_id)
        if not file.is_file():
            continue
        shown = file.relative_to(root).as_posix()
        try:
            content = json.loads(file.read_text(encoding="utf-8"))
        except json.JSONDecodeError as e:
            problems.append(Problem(shown, "", f"invalid JSON: {e.msg} (line {e.lineno})"))
            continue
        if not isinstance(content, dict) or "response" not in content:
            problems.append(Problem(shown, "", "must be an object with a 'response' key"))
            continue
        endpoint["example_response"] = content["response"]
    return problems


def _orphan_examples(root: Path, sources: Mapping[str, Source]) -> list[Problem]:
    """Example files whose source or endpoint no longer exists (removed or renamed)."""
    examples_dir = root / "examples"
    if not examples_dir.is_dir():
        return []
    problems = []
    for folder in sorted(p for p in examples_dir.iterdir() if p.is_dir()):
        source = sources.get(folder.name)
        if source is None:
            if not (root / "sources" / f"{folder.name}.yaml").exists():
                problems.append(Problem(f"examples/{folder.name}", "", "no source with this id"))
            continue  # a source that failed to load is reported on its own
        endpoint_ids = {e.id for e in source.endpoints}
        for file in sorted(folder.glob("*.json")):
            if file.stem not in endpoint_ids:
                problems.append(
                    Problem(
                        f"examples/{folder.name}/{file.name}",
                        "",
                        f"no endpoint {file.stem!r} in {folder.name}.yaml",
                    )
                )
    return problems


class _UniqueKeyLoader(yaml.SafeLoader):
    """SafeLoader that rejects duplicate keys.

    Plain YAML loading silently keeps the last of two identical keys, so a duplicated
    `path:` would quietly override the first. SafeLoader (not yaml.Loader) also means
    YAML can never construct arbitrary Python objects.
    """

    def construct_mapping(self, node: yaml.MappingNode, deep: bool = False) -> dict[Any, Any]:
        seen: set[Any] = set()
        for key_node, _ in node.value:
            key = self.construct_object(key_node, deep=deep)
            if key in seen:
                raise yaml.constructor.ConstructorError(
                    None, None, f"duplicate key {key!r}", key_node.start_mark
                )
            seen.add(key)
        return super().construct_mapping(node, deep=deep)


def _yaml_message(error: yaml.YAMLError) -> str:
    mark = getattr(error, "problem_mark", None)
    problem = getattr(error, "problem", None) or str(error)
    return f"{problem} (line {mark.line + 1})" if mark is not None else problem


def _root_causes(error: ValidationError) -> list[ErrorDetails]:
    """Drop knock-on errors.

    When an endpoint fails, Pydantic also reports "endpoints should have at least 1
    item" because no valid endpoint is left. That is a consequence, not a mistake, so
    skip a too_short error when a deeper error exists under the same location.
    """
    errors = error.errors()
    return [
        err
        for err in errors
        if not (
            err["type"] == "too_short"
            and any(
                len(o["loc"]) > len(err["loc"]) and o["loc"][: len(err["loc"])] == err["loc"]
                for o in errors
            )
        )
    ]


def _location(loc: tuple[int | str, ...], data: Any) -> str:
    """Render ("endpoints", 0, "path") as "endpoints[0] (drug_label).path".

    Adds the item's id after list indexes when there is one, so the reader doesn't
    have to count entries in a long file.
    """
    text = ""
    node = data
    for part in loc:
        if isinstance(part, int):
            text += f"[{part}]"
            node = node[part] if isinstance(node, list) and part < len(node) else None
            if isinstance(node, dict) and isinstance(node.get("id"), str):
                text += f" ({node['id']})"
        else:
            text += f".{part}" if text else part
            node = node.get(part) if isinstance(node, dict) else None
    return text


def _message(err: ErrorDetails) -> str:
    if err["type"] == "extra_forbidden":
        return "unknown field (typo?)"
    if err["type"] == "missing":
        return "required field is missing"
    return err["msg"].removeprefix("Value error, ")
